def launch_checklist_text() -> str:
    lines = ["✅ **Launch Checklist**", "", "Перед показом клиенту или запуском своего канала пройдите этот список:", ""]
    for idx, item in enumerate(LAUNCH_CHECKS, start=1):
        lines.append(f"**{idx}. {item.title}**")
        lines.append(f"Команда: `{item.command}`")
        lines.append(f"Ожидание: {item.expected}")
        lines.append("")
    lines.append("Если любой пункт ведёт себя странно — сначала исправьте его, потом показывайте систему клиенту.")
    return "\n".join(lines).strip()


